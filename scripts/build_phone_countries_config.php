$flagForIso = static function (string $iso): string {
    $iso = strtoupper($iso);
    if (strlen($iso) !== 2) {
        return '';
    }

    return mb_chr(0x1F1E6 + ord($iso[0]) - 65).mb_chr(0x1F1E6 + ord($iso[1]) - 65);
};

